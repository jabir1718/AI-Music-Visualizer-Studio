'use strict';
const assert=require('assert');
const type=require('../typography-studio.js');
assert.strictEqual(type.fonts.length,100,'catalogue must contain 100 fonts');
assert.strictEqual(new Set(type.fonts).size,100,'font names must be unique');
const state=type.setAll({title:{family:'Orbitron',weight:900,scale:1.5,spacing:3,depth:8,outline:2,glow:14},lyric:{family:'not-a-font',depth:99}});
assert.strictEqual(state.title.family,'Orbitron');
assert.strictEqual(state.title.weight,900);
assert.strictEqual(state.title.scale,1.5);
assert.strictEqual(state.title.depth,8);
assert.strictEqual(state.lyric.family,'Montserrat','invalid fonts fall back safely');
assert.strictEqual(state.lyric.depth,18,'depth is bounded');
const fake={font:'',letterSpacing:'0px',lineJoin:'miter',lineWidth:1,strokeStyle:'#000',shadowColor:'',shadowBlur:0};
type.apply(fake,'title',40,'sans-serif');
assert.match(fake.font,/900 60px "Orbitron"/);
assert.strictEqual(fake.letterSpacing,'3px');
assert.strictEqual(fake.lineWidth,2);
const calls=[];
const ctx={fillStyle:'#fff',shadowBlur:0,shadowColor:'',lineWidth:1,strokeStyle:'#000',save(){},restore(){},strokeText(...a){calls.push(['stroke',...a])},fillText(...a){calls.push(['fill',...a])}};
type.drawGlyph(ctx,'title','WaveForge',10,20,400);
assert(calls.some(x=>x[0]==='fill'));
assert(calls.filter(x=>x[0]==='stroke').length>=2,'depth and outline should render strokes');
console.log('Typography studio tests passed.');
