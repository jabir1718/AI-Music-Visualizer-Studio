'use strict';
const assert=require('assert');
const assistant=require('../offline-edit-assistant.js');
const result=assistant.parsePrompt('Make it cinematic, 9:16, bass +3 dB, title to Night Drive',{mainBass:0});
const values=Object.fromEntries(result.actions.map(x=>[x.id,x.value]));
assert.strictEqual(values.autoVideoStyle,'cinematic');
assert.strictEqual(values.exportRatio,'9:16');
assert.strictEqual(values.mainBass,3);
assert.strictEqual(values.titleInput,'Night Drive');
assert.ok(result.actions.length>=4,'multiple supported edits should be previewed');
const volume=assistant.parsePrompt('set volume 70% and lyrics bigger',{lyricSize:48});
const v=Object.fromEntries(volume.actions.map(x=>[x.id,x.value]));
assert.strictEqual(v.volume,.7);
assert.strictEqual(v.lyricSize,58);
const roman=assistant.parsePrompt('Cinematic style, 9:16, bass +3 dB, title ko Night Drive rakho, cuts tez karo',{mainBass:0,autoVideoIntensity:3});
const rv=Object.fromEntries(roman.actions.map(x=>[x.id,x.value]));
assert.strictEqual(rv.autoVideoStyle,'cinematic','Roman Urdu mixed prompts should select a template');
assert.strictEqual(rv.exportRatio,'9:16');
assert.strictEqual(rv.mainBass,3);
assert.strictEqual(rv.titleInput,'Night Drive');
assert.strictEqual(rv.autoVideoIntensity,4);
const photo=assistant.parsePrompt('photo memories lagao, awaz 70 percent, lyrics bara karo');
const pv=Object.fromEntries(photo.actions.map(x=>[x.id,x.value]));
assert.strictEqual(pv.autoVideoStyle,'photo');
assert.strictEqual(pv.volume,.7);
assert.strictEqual(pv.lyricSize,58);
const unsupported=assistant.parsePrompt('make a 3D dragon walk through the city');
assert.strictEqual(unsupported.actions.length,0,'unsupported AI requests must not be guessed or executed');
assert.ok(unsupported.unsupported.length);
const mixed=assistant.parsePrompt('title to Night Drive, bass +3 dB');
const mixedValues=Object.fromEntries(mixed.actions.map(x=>[x.id,x.value]));
assert.strictEqual(mixedValues.titleInput,'Night Drive','title text should stop at the command separator');
assert.strictEqual(mixedValues.mainBass,3);
console.log('Offline assistant tests passed: English and Roman Urdu prompts, supported values, preview safety and unsupported request rejection.');
