'use strict';
const assert=require('assert');
const k=require('../keyframe-engine.js');
let frames=k.upsert([],0,{x:.2,y:.3,scale:1,rotation:0,opacity:1});
frames=k.upsert(frames,4,{x:.8,y:.7,scale:2,rotation:90,opacity:.5});
assert.strictEqual(frames.length,2);
assert.strictEqual(k.evaluate(frames,0,{x:.5}).x,.2);
const middle=k.evaluate(frames,2);
assert(Math.abs(middle.x-.5)<1e-9,'smoothstep midpoint should interpolate halfway');
assert(Math.abs(middle.rotation-45)<1e-9);
assert.strictEqual(k.evaluate(frames,8).scale,2,'last keyframe holds after its time');
assert.strictEqual(k.evaluate(frames,-1,{x:.4}).x,.4,'base state holds before first keyframe');
frames=k.upsert(frames,4.02,{x:.9,y:.7,scale:2,rotation:90,opacity:.5});
assert.strictEqual(frames.length,2,'nearby keyframes update instead of duplicating');
const removed=k.removeNearest(frames,4,.2);
assert.strictEqual(removed.frames.length,1);
assert.strictEqual(removed.removed.time,4.02);
assert.strictEqual(k.removeNearest(frames,20,.2).removed,null);
console.log('Object keyframe animation tests passed.');
