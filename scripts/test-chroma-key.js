'use strict';
const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const window={};
vm.runInNewContext(fs.readFileSync('chroma-key.js','utf8'),{window,document:{getElementById:()=>null},Math,Number,String,parseInt});
const api=window.WaveForgeChromaKey;
assert(api,'Chroma key API should load');
const pixels=new Uint8ClampedArray([0,255,0,255,255,0,0,255,0,150,0,255]);
api.set({keyColor:'#00ff00',tolerance:88,softness:38,spill:55,enabled:true});
api.processPixels(pixels);
assert.equal(pixels[3],0,'Exact key-color pixel should become transparent');
assert.equal(pixels[7],255,'Non-key red pixel should remain opaque');
assert(pixels[11]>0&&pixels[11]<255,'Soft edge should produce partial alpha');
assert(pixels[9]<150,'Green spill should be reduced on edge pixels');
api.set({enabled:false,keyColor:'#0000ff'});
assert.equal(api.getSettings().enabled,false);
assert.equal(api.getSettings().keyColor,'#0000ff');
console.log('Chroma key pixel-processing tests passed.');
