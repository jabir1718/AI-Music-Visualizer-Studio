'use strict';
const assert=require('assert');
const studio=require('../three-studio.js');
const source=require('fs').readFileSync(require('path').join(__dirname,'..','three-studio.js'),'utf8');
assert(studio.SHAPES.length>=8,'3D studio should expose multiple primitive geometries');
assert(studio.SHAPES.includes('torus-knot'));
assert(studio.SHAPES.includes('text'),'3D text must be a supported geometry type');
assert(studio.FONT_FAMILIES.length>=8,'3D text should offer multiple font families');
const cfg=studio.normalizeConfig({shape:'bad',color:'red',scale:9,rotationX:240,metalness:-1,roughness:2,light:9,positionX:9,positionY:-9,positionZ:0,autoRotate:false});
assert.strictEqual(cfg.shape,'torus-knot');
assert.strictEqual(cfg.color,'#57d8ff');
assert.strictEqual(cfg.scale,2.5);
assert.strictEqual(cfg.rotationX,180);
assert.strictEqual(cfg.metalness,0);
assert.strictEqual(cfg.roughness,1);
assert.strictEqual(cfg.light,3);
assert.strictEqual(cfg.positionX,1.5);
assert.strictEqual(cfg.positionY,-1.5);
assert.strictEqual(cfg.positionZ,0);
assert.strictEqual(cfg.autoRotate,false);
const clean=studio.normalizeConfig({shape:'sphere',color:'#ff00aa',scale:1.4,rotationY:45});
assert.strictEqual(clean.shape,'sphere');
assert.strictEqual(clean.color,'#ff00aa');
assert.strictEqual(clean.scale,1.4);
assert.strictEqual(clean.rotationY,45);
const text=studio.normalizeConfig({shape:'text',text:'WAVEFORGE 3D',textDepth:.42});
assert.strictEqual(text.shape,'text');assert.strictEqual(text.text,'WAVEFORGE 3D');assert.strictEqual(text.textDepth,.42);
assert.strictEqual(text.fontFamily,'helvetiker_bold');
const optimer=studio.normalizeConfig({shape:'text',fontFamily:'optimer_regular'});
assert.strictEqual(optimer.fontFamily,'optimer_regular');
assert.strictEqual(studio.normalizeConfig({fontFamily:'not-a-font'}).fontFamily,'helvetiker_bold');
assert(/threeFont/.test(source)&&/FONT_FAMILIES\.map/.test(source),'3D text font selector is missing');
assert(/function syncControls\(\)/.test(source)&&/await setShape\(config\.shape\);syncControls\(\)/.test(source),'Saved 3D object controls must be restored into the UI');
assert(/loadAsync\(FONT_URLS\[selected\]\)/.test(source),'Selected 3D font must be loaded from its own typeface file');
assert(/TextGeometryClass/.test(source)&&/depth:config\.textDepth/.test(source),'3D text must use extruded TextGeometry depth');
assert(/loadTextTools/.test(source),'3D font and text addons should load lazily');
assert.strictEqual(studio.getSettings().overlayEnabled,false);
const saved=studio.setSettings({shape:'sphere',overlayEnabled:true,overlayScale:.7,overlayX:.3,overlayY:.65});
assert.strictEqual(saved.shape,'sphere');assert.strictEqual(saved.overlayEnabled,true);
assert.strictEqual(saved.overlayScale,.7);assert.strictEqual(saved.overlayX,.3);assert.strictEqual(saved.overlayY,.65);
assert.strictEqual(studio.drawToCanvas({},100,100),false,'must safely skip canvas compositing until WebGL scene is initialized');
studio.setSettings({overlayEnabled:false});
console.log('3D object studio tests passed.');
