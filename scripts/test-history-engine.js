'use strict';
const assert=require('assert');
const history=require('../history-engine.js');
const h=history.create({limit:3,delay:0});
h.seed({text:'A'});
h.record({text:'B'});h.flush();
h.record({text:'C'});h.flush();
assert.deepStrictEqual(h.undo(),{text:'B'});
assert.deepStrictEqual(h.undo(),{text:'A'});
assert.strictEqual(h.canUndo(),false);
assert.deepStrictEqual(h.redo(),{text:'B'});
h.record({text:'D'});h.flush();
assert.strictEqual(h.canRedo(),false,'new edit clears redo history');
h.record({text:'E'});h.flush();
h.record({text:'F'});h.flush();
assert.deepStrictEqual(h.undo(),{text:'E'});
assert.strictEqual(h.canUndo(),true);
h.clear();assert.strictEqual(h.canUndo(),false);assert.strictEqual(h.canRedo(),false);
console.log('Visual history undo/redo tests passed.');
