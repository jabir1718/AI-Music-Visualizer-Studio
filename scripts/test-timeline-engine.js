'use strict';
const assert=require('assert');
const timeline=require('../timeline-engine.js');
const layer={offset:2,rate:1,trimStart:3,trimEnd:8,loop:false};
assert.deepStrictEqual({...timeline.resolveLayerTime(layer,1,12)},{active:false,currentTime:3,reason:'before-start'});
assert.deepStrictEqual({...timeline.resolveLayerTime(layer,4,12)},{active:true,currentTime:5,reason:'playing'});
assert.deepStrictEqual({...timeline.resolveLayerTime(layer,8,12)},{active:false,currentTime:8,reason:'after-end'});
const loop={...layer,loop:true};
assert.strictEqual(timeline.resolveLayerTime(loop,8,12).currentTime,6,'loop wraps within trimmed section');
const split=timeline.splitLayer(layer,4,12);
assert(Math.abs(split.splitMediaTime-5)<1e-9);
assert.strictEqual(split.first.trimEnd,5);
assert.strictEqual(split.second.trimStart,5);
assert.strictEqual(split.second.offset,4);
assert.strictEqual(timeline.splitLayer(layer,2,12),null,'cannot split before clip begins');
const edited={trimStart:0,trimEnd:0};
const b=timeline.setTrim(edited,2,7,10);
assert.strictEqual(b.start,2);assert.strictEqual(b.end,7);
assert.strictEqual(timeline.setTrim(edited,8,3,10).valid,false,'invalid trim window rejected');
console.log('Timeline trim, loop and split tests passed.');
