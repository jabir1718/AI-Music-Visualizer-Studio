'use strict';
const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
const source=fs.readFileSync('filter-studio.js','utf8');
const window={};
vm.runInNewContext(source,{window,document:{getElementById:()=>null},Number,String,Math});
const api=window.WaveForgeFilters;
assert(api,'Filter API did not load');
assert.strictEqual(api.items.length,50,'Expected exactly 50 named filter presets');
assert.strictEqual(new Set(api.items.map(x=>x.name)).size,50,'Filter names must be unique');
assert(new Set(api.items.map(x=>x.group)).size>=8,'Expected multiple filter families');
assert(api.items.every(x=>Number.isFinite(x.brightness)&&Number.isFinite(x.contrast)&&Number.isFinite(x.saturate)),'Filter parameters must be numeric');
let drawn=0;
const ctx={filter:'none',globalAlpha:1,globalCompositeOperation:'source-over',save(){},restore(){},drawImage(){drawn++;},fillRect(){},set fillStyle(v){this._fill=v;}};
api.set('f02',65);api.draw(ctx,{},0,0,100,100);
assert.strictEqual(drawn,1,'Selected filter must draw source media');
assert.strictEqual(ctx.filter,'none','Canvas filter state must not leak into visualizer layers');
assert.strictEqual(api.getSettings().filterPreset,'f02');
assert.strictEqual(api.getSettings().filterIntensity,65);
api.set('f01',0);api.draw(ctx,{},0,0,100,100);
assert.strictEqual(drawn,2);
console.log('50-filter catalogue and canvas-application tests passed.');
